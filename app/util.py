# Порядок групп в деревьях отчётов (РНП заказы, РНП юнит-экономика,
# Продажи шт., Цены). Согласовано 2026-09-11:
#   L1  — фиксированный список: сначала ECOM, затем ТД «АВТОПРОФИ»,
#         остальные (в т.ч. новые) — после них по алфавиту;
#   L2  — по алфавиту;
#   L3  — по алфавиту;
#   L4  — по seller_article (по возрастанию).
# Метрика больше НЕ участвует в сортировке ни на одном уровне: позиция
# категории не должна «прыгать» при смене периода.
# ---------------------------------------------------------------------------

# Фиксированный порядок первого уровня. Сопоставление — по подстроке в
# верхнем регистре, чтобы устоять к кавычкам/пробелам в названии
# («Продукция ТД "АВТОПРОФИ"» vs «Продукция ТД «АВТОПРОФИ»»).
L1_FIXED_ORDER = ("ECOM", "АВТОПРОФИ")


def l1_rank(name) -> int:
    """Индекс группы L1 в фиксированном порядке; неизвестные — в конец."""
    s = (name or "").strip().upper()
    for i, token in enumerate(L1_FIXED_ORDER):
        if token in s:
            return i
    return len(L1_FIXED_ORDER)


def l1_sort_key(name):
    """Ключ сортировки L1: (фиксированный ранг, алфавит)."""
    return (l1_rank(name), (name or "").strip().lower())


def cat_sort_key(name):
    """Ключ сортировки L2/L3: алфавит (регистронезависимо)."""
    return (name or "").strip().lower()
