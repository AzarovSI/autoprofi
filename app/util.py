# -*- coding: utf-8 -*-
"""Общие утилиты приложения (единый источник правды).

Здесь живёт канонизация артикула продавца — её используют ВСЕ точки
записи (загрузчик отчётов и ручное редактирование/импорт справочника),
чтобы один и тот же товар на разных маркетплейсах не плодил дубли
из-за разницы в регистре/пробелах.
"""
import re


# Кириллические буквы, визуально неотличимые от латинских (гомоглифы).
# При вводе артикулов вручную/в Excel легко случайно набрать кириллическую
# «К» вместо латинской «K» — для базы это РАЗНЫЕ символы, и один товар
# плодит дубли (напр. EDP24-20K vs EDP24-20К). Приводим кириллицу к
# латинице ДО перевода в верхний регистр, чтобы такие артикулы схлопывались
# в один ключ. Карта только для однозначных гомоглифов (строчные тоже —
# на случай ввода до .upper()).
_CYR2LAT = {
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H",
    "О": "O", "Р": "P", "С": "C", "Т": "T", "У": "Y", "Х": "X",
    "а": "a", "в": "b", "е": "e", "к": "k", "м": "m", "н": "h",
    "о": "o", "р": "p", "с": "c", "т": "t", "у": "y", "х": "x",
}
_CYR2LAT_TABLE = {ord(k): v for k, v in _CYR2LAT.items()}

_LAT_RE = re.compile(r"[A-Za-z0-9]")
_CYR_RE = re.compile(r"[\u0400-\u04FF]")


def _is_lat(ch: str) -> bool:
    return bool(ch) and bool(_LAT_RE.match(ch))


def _is_cyr_letter(ch: str) -> bool:
    return bool(ch) and bool(_CYR_RE.match(ch))


def _fix_homoglyphs(s: str) -> str:
    """Заменить кириллический гомоглиф на латиницу ТОЛЬКО когда он явно
    «вклинен» в латинский/цифровой контекст: хотя бы один сосед
    (слева или справа, без учёта пробелов) — латинская буква/цифра
    И рядом НЕТ другой кириллицы (т.е. это не русское слово).

    Примеры замены: EDP24-20К → EDP24-20K; DP-25/365 К → DP-25/365 K
    («К» после пробела, но предыдущий значимый символ — цифра «5»).
    НЕ трогаем: «ГЛУБОКИЙ ЧЕРНЫЙ», «НЕОПОЗНАННЫЙ ТОВАР» — там каждая
    кириллическая буква окружена кириллицей.
    """
    if not _CYR_RE.search(s):
        return s
    chars = list(s)
    n = len(chars)

    def prev_sig(i):
        j = i - 1
        while j >= 0 and chars[j] == " ":
            j -= 1
        return chars[j] if j >= 0 else ""

    def next_sig(i):
        j = i + 1
        while j < n and chars[j] == " ":
            j += 1
        return chars[j] if j < n else ""

    out = []
    for i, ch in enumerate(chars):
        repl = _CYR2LAT.get(ch)
        if repl is not None:
            p, nx = prev_sig(i), next_sig(i)
            # сосед — латиница/цифра, и ни один сосед не кириллица
            lat_neighbor = _is_lat(p) or _is_lat(nx)
            cyr_neighbor = _is_cyr_letter(p) or _is_cyr_letter(nx)
            if lat_neighbor and not cyr_neighbor:
                out.append(repl)
                continue
        out.append(ch)
    return "".join(out)


def canon_article(s) -> str:
    """Канонизация артикула продавца к единому виду для сопоставления.

    Правила: обрезаем крайние пробелы, схлопываем внутренние повторные
    пробелы в один, в «смешанных» токенах заменяем кириллические
    гомоглифы на латиницу, переводим буквы в ВЕРХНИЙ регистр.
    Прочие символы (дефисы, цифры, спецсимволы) не трогаем.
    Пусто/None → ''.

    Это ЕДИНСТВЕННЫЙ источник правды: применяется на всех точках ЗАПИСИ
    seller_article, чтобы «AGR-140 Smerch» и «AGR-140 SMERCH» давали один
    ключ, а «EDP24-20K» (лат.) и «EDP24-20К» (кир.) не плодили дубли.
    """
    if not s:
        return ""
    s = re.sub(r"\s+", " ", str(s).strip())
    s = _fix_homoglyphs(s)
    return s.upper()


